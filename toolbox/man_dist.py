"""
Carry the generated man pages into the source archive

Run by 'meson dist'. The man pages are generated by 'make gen-man-pages' and not
committed, so the archive, made from the committed tree, has none. This copies
each folder of 'man' that 'make gen-man-pages' filled, the pages and the
meson.build installing them, from MESON_SOURCE_ROOT into MESON_DIST_ROOT. When
there are none, the archive is made without man pages.
"""
import os
import shutil
import sys
from pathlib import Path

FOLDERS = ["examples", "tests", "tools"]


def main():
    src = Path(os.environ["MESON_SOURCE_ROOT"]) / "man"
    dst = Path(os.environ["MESON_DIST_ROOT"]) / "man"

    found = [name for name in FOLDERS if (src / name / "meson.build").is_file()]
    if not found:
        print("man_dist: no generated man pages; the archive has none", file=sys.stderr)
        return 0

    for name in found:
        shutil.copytree(src / name, dst / name, dirs_exist_ok=True)

    return 0


if __name__ == "__main__":
    sys.exit(main())
